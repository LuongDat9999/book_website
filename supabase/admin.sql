create or replace function public.verify_admin(p_username text, p_password text)
returns boolean language sql stable security definer set search_path = public
as $$ select exists (select 1 from public.admin_accounts where username = p_username and password_hash = extensions.crypt(p_password::text, password_hash::text)) $$;

alter table public.articles enable row level security;

drop policy if exists "Public can read published articles" on public.articles;
create policy "Public can read published articles" on public.articles for select using (published = true);
drop policy if exists "Admins can manage articles" on public.articles;
drop policy if exists "Admins can manage books" on public.books;
drop policy if exists "Admins can read contacts" on public.contacts;
drop policy if exists "Admins can update contacts" on public.contacts;
