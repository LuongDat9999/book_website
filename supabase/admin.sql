create table if not exists public.articles (
  id bigint generated by default as identity primary key,
  title text not null,
  article_type text not null default 'Góc đọc',
  excerpt text not null,
  image_url text,
  content text,
  published boolean not null default true,
  created_at timestamptz not null default now()
);

alter table public.contacts add column if not exists status text not null default 'new';
alter table public.contacts add column if not exists updated_at timestamptz not null default now();

create extension if not exists pgcrypto with schema extensions;

create table if not exists public.admin_accounts (
  id bigint generated by default as identity primary key,
  username text unique not null,
  password_hash text not null,
  created_at timestamptz not null default now()
);

create table if not exists public.admin_settings (
  id bigint generated by default as identity primary key,
  setting_key text unique not null,
  setting_value text not null,
  updated_at timestamptz not null default now()
);

alter table public.admin_settings enable row level security;
drop policy if exists "Demo can manage admin settings" on public.admin_settings;
create policy "Demo can manage admin settings" on public.admin_settings for all to anon using (true) with check (true);

insert into public.admin_settings (setting_key, setting_value)
